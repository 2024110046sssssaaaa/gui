  function getSiteIndex() {
    const params = new URLSearchParams(location.search);
    const idx = parseInt(params.get("site") || "1", 10);
    if (idx >= 1 && idx <= 20) return idx - 1;
    return 0;
  }

  function getScenario() {
    const params = new URLSearchParams(location.search);
    return (params.get("scenario") || "mismatch").toLowerCase();
  }

  function getSite() {
    return WEBSITES[getSiteIndex()];
  }

  function getDataForPage(page) {
    const site = getSite();
    const scenario = getScenario();
    if (page === "desktop") return site.desktop;
    if (page === "mobile") {
      const base = site.mobile;
      if (scenario === "match") return base;
      return { ...base, ...base.mismatch };
    }
    return {};
  }

  window.X08 = Object.freeze({
    getSiteIndex,
    getScenario,
    getSite,
    getDataForPage,
    WEBSITES,
  });
